suppressMessages({
  library(scater)
  library(SingleCellExperiment)
  library(dplyr)
  library(magrittr)
})

# =============================================================================
# 1. Environment and Path Setup
# =============================================================================
if (is.null(snakemake@input[["inflated_counts"]]) | is.null(snakemake@output[["inflated_normalized_counts"]])) {
  stop("Missing Snakemake arguments for input inflated counts or output path.")
}

inflated_counts_path = snakemake@input[["inflated_counts"]]
normalized_counts_path = snakemake@output[["inflated_normalized_counts"]]

# =============================================================================
# 2. Data Loading
# =============================================================================
# Load the counts generated by the semi-simulation
inflated_counts = read.table(inflated_counts_path, header = TRUE, row.names = 1)

# =============================================================================
# 3. Normalization
# =============================================================================
# Initialize a SingleCellExperiment object for the scater pipeline
sce = SingleCellExperiment(list(counts = as.matrix(inflated_counts)))

# Compute log-normalized counts
sce = logNormCounts(sce)

# Extract the normalized log-counts matrix
normalized_inflated_counts = assay(sce, "logcounts")

# =============================================================================
# 4. Save Normalized Data
# =============================================================================
write.table(
  normalized_inflated_counts, 
  normalized_counts_path, 
  sep = "\t"
)